"""Integrated market analysis pipeline with a hard data-quality gate."""
from __future__ import annotations

from market_intelligence.quality_gate import assess_candles, QualityConfig
from market_intelligence.analysis import analyze_market
from market_intelligence.screener import calculate_screening_metrics


def evaluate_market_data(df, interval_minutes=5, now=None, quality_config=None, symbol=None):
    """Analyze data, but mark it strategy-ineligible when the quality gate fails.

    This does not create a trading signal or place orders.
    """
    quality = assess_candles(
        df, interval_minutes=interval_minutes, now=now, config=quality_config
    )
    if df is None or df.empty:
        return {
            "status": "no_data",
            "symbol": symbol,
            "trade_eligible": False,
            "quality": quality,
            "technical_analysis": None,
            "screening": None,
            "blocking_reasons": quality.get("blocking_reasons", ["No data"]),
        }

    technical = analyze_market(df)
    screening = calculate_screening_metrics(df)

    # Data-quality failure is a hard gate. Analysis can be displayed for
    # diagnostics, but downstream strategy code must honor trade_eligible.
    eligible = bool(quality["trade_eligible"])
    return {
        "status": "READY_FOR_STRATEGY" if eligible else "BLOCKED",
        "symbol": symbol,
        "trade_eligible": eligible,
        "quality": quality,
        "technical_analysis": technical,
        "screening": screening,
        "blocking_reasons": list(quality["blocking_reasons"]),
        "warning": (
            "No trade signal is generated by this module. "
            "A strategy and risk engine must make the next decision."
        ),
    }
